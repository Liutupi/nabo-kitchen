"""Reproducible registration and review sheets for the 127 missing dish heroes.

Only uniform image resizing is performed; food is generated by the image tool.
Existing heroes and recipe contents are never overwritten.
"""
import argparse
import csv
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

BATCH = Path(__file__).resolve().parent
ROOT = BATCH.parents[4]
ART = ROOT / "game-art/kitchen"
HERO = ART / "dish-hero"
QUEUE = BATCH / "manifest.json"
REFERENCE = "game-art/kitchen/dish-hero/hero_xilanhua-chaoshanbei.png"


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save(value):
    value["updated_utc"] = datetime.now(timezone.utc).isoformat()
    QUEUE.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def init():
    if QUEUE.exists():
        raise SystemExit("Manifest already exists; resume it instead of replacing it.")
    names = {x["id"]: x["name"] for x in json.loads((ROOT / "data/ingredients.json").read_text(encoding="utf-8"))["ingredients"]}
    vessels = {"plate": "white round porcelain plate", "deep": "white deep porcelain plate", "bowl": "white porcelain soup bowl", "oval": "white oval fish platter", "claypot": "small dark earthenware casserole", "steamer": "open bamboo steamer"}
    recipes = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "data/recipes/curated").glob("*.json"))]
    priority = ["fanqie-chaodan", "suanrong-caixin", "qingzheng-luyu", "fanqie-dantang", "baiqie-ji", "hongshao-paigu", "kele-jichi", "xianggu-menji", "hongshao-rou", "qingjiao-rousi", "yangcong-chao-niurou", "hongshao-yu", "baizhuo-xia", "xiaren-chaodan", "roubing-zhengdan", "suanrong-shengcai", "culiu-baicai", "chao-xilanhua", "suanla-tudousi", "hongshao-qiezi", "hupi-qingjiao", "jiachang-doufu", "xiangjian-doufu", "zheng-shuidan", "pai-huanggua", "qingcai-doufu-tang", "jiyu-doufu-tang", "fanqie-tudou-niurou-tang"]
    recipes.sort(key=lambda r: (priority.index(r["id"]) if r["id"] in priority else 1000, r["id"]))
    items = []
    for r in recipes:
        ident = "hero_" + r["id"]
        if (HERO / (ident + ".png")).exists():
            continue
        ingredients = ", ".join(names[x["id"]] + (" (main)" if x.get("main") else "") for x in r["ingredients"])
        steps = " ".join(x["text"] for x in r["steps"])
        prompt = ("Use case: stylized-concept. Create ONE complete Chinese home-cooked dish illustration for the NABO kitchen game, asset " + ident + ". "
            "Reference image is STYLE ONLY: match its cute rounded flat 2D food shapes, warm vivid appetizing colors, solid dark-brown #3B2730 outlines, one light and one shadow cel-shaded plane, crisp small glossy highlights. "
            "NEW SUBJECT: " + r["name"] + ". Actual recipe ingredients: " + ingredients + ". Preparation reference: " + steps + ". "
            "Illustrate the FINISHED cooked dish accurately; the main ingredient must be recognizable. Do not copy the reference's scallops, broccoli or garlic unless this recipe actually contains them. "
            "Serve in a " + vessels[r["dish"]["vessel"]] + ". Three-quarter overhead view about 45 degrees, upper-left light. "
            "Landscape 4:3 transparent canvas; compose for 640x480, vessel center (320,270), whole vessel including rim inside frame, generous transparent margins on every side. "
            "A single isolated dish only, no food faces, no characters, no spoons/chopsticks, no text, no labels, no logos, no decorations, no steam/fire/effects, no tabletop/background, no white sticker border, no photorealism, no 3D, no smooth gradients. Real transparent RGBA background. Distinct readable food silhouettes at 160x120.")
        items.append({"id": ident, "recipe_id": r["id"], "name": r["name"], "recipe_sha256": digest(ROOT / "data/recipes/curated" / (r["id"] + ".json")), "status": "todo", "prompt": prompt})
    save({"schema": 1, "batch": "2026-10-29", "source_branch": "codex/kitchen-model", "source_commit": "c31bae7d4d50c5e25a282696f787317bc3636b93", "generator": "OpenAI imagegen built-in tool", "reference": REFERENCE, "reference_sha256": digest(ROOT / REFERENCE), "initial_recipe_count": len(recipes), "initial_existing_heroes": len(recipes) - len(items), "initial_missing": len(items), "work_state": "active", "items": items})


def ingest(ident, original):
    value = json.loads(QUEUE.read_text(encoding="utf-8"))
    item = next(x for x in value["items"] if x["id"] == ident)
    target = HERO / (ident + ".png")
    if target.exists():
        raise SystemExit("Existing delivery: refusing overwrite " + ident)
    source = Path(original)
    original_target = HERO / "originals" / (ident + "-source.png")
    with Image.open(source) as raw:
        if raw.mode != "RGBA" or raw.getchannel("A").getextrema() != (0, 255):
            raise SystemExit("Requires actual transparent RGBA from generator")
        if abs(raw.width / raw.height - 4 / 3) > 0.015:
            raise SystemExit("Requires 4:3 canvas; no crop or distorted resize")
        dimensions = list(raw.size)
        resized = raw.resize((640, 480), Image.Resampling.LANCZOS)
        box = resized.getchannel("A").point(lambda a: 255 if a >= 128 else 0).getbbox()
        if not box or box[0] < 4 or box[1] < 4 or box[2] > 636 or box[3] > 476:
            raise SystemExit("Clipped or insufficient transparent margin")
        original_target.parent.mkdir(exist_ok=True)
        shutil.copyfile(source, original_target)
        resized.save(target)
    metadata = {"id": ident, "recipe_id": item["recipe_id"], "status": "review", "generator": value["generator"], "original": "originals/" + original_target.name, "original_sha256": digest(original_target), "original_dimensions": dimensions, "asset_dimensions": [640, 480], "asset_sha256": digest(target), "references": [REFERENCE], "prompt": item["prompt"], "recipe_sha256": item["recipe_sha256"], "processing": "Uniform Lanczos resize of entire original transparent RGBA canvas to 640x480; no crop, repaint or alpha removal.", "review": "待逐图审美、真实菜品准确度及实机验收。"}
    (HERO / (ident + ".json")).write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    asset_file = ART / "ASSET_LIST.csv"
    with asset_file.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    if any(x["id"] == ident for x in rows):
        raise SystemExit("Asset already registered; inspect instead of duplicate")
    with asset_file.open("a", encoding="utf-8", newline="") as f:
        csv.writer(f, lineterminator="\n").writerow([ident, "hero", "dish-hero/" + ident + ".png", "160x120", "640x480", "0.1", "Codex", "review", item["name"] + "完整菜图；2026-10-29 补图批次，待逐图审美、准确度及实机验收"])
    item.update(status="review", asset_sha256=metadata["asset_sha256"], original_sha256=metadata["original_sha256"])
    save(value)
    print(ident, "review", box)


def sheets(decoded=None):
    value = json.loads(QUEUE.read_text(encoding="utf-8"))
    items = [x for x in value["items"] if x["status"] == "review"]
    font = None
    for candidate in ["C:/Windows/Fonts/msyh.ttc", "/System/Library/Fonts/PingFang.ttc", "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"]:
        if Path(candidate).is_file():
            font = ImageFont.truetype(candidate, 15)
            break
    if font is None:
        font = ImageFont.load_default(size=13)
    for page in range((len(items) + 11) // 12):
        part = items[page * 12: (page + 1) * 12]
        sheet = Image.new("RGB", (1020, 660), "#15122A")
        draw = ImageDraw.Draw(sheet)
        for index, item in enumerate(part):
            x, y = (index % 3) * 340, (index // 3) * 165
            draw.text((x + 8, y + 2), item["name"] if font.size == 15 else item["recipe_id"], fill="#FBF1E3", font=font)
            if decoded is None:
                small = Image.open(HERO / (item["id"] + ".png")).resize((160, 120), Image.Resampling.LANCZOS)
            else:
                small = Image.open(Path(decoded) / (item["id"] + ".png")).convert("RGBA")
                if small.size != (160, 120):
                    raise SystemExit("Decoded proof must be actual 160x120 frame")
            for side, bg in enumerate(["#2C2845", "#FBF1E3"]):
                card = Image.new("RGBA", (160, 120), bg)
                card.alpha_composite(small)
                rgb = card.convert("RGB")
                # Match asset_codec.rgb565 bit truncation and expand565 exactly.
                rgb = Image.merge("RGB", [rgb.getchannel(c).point(lambda v, b=b: ((v >> (8 - b)) * 255 + ((1 << b) - 1) // 2) // ((1 << b) - 1)) for c, b in [("R", 5), ("G", 6), ("B", 5)]])
                sheet.paste(rgb, (x + 5 + side * 168, y + 27))
        prefix = "review" if decoded is None else "decoded-review"
        sheet.save(BATCH / (prefix + "-%02d.png" % (page + 1)))
    print(json.dumps({"delivered": len(items), "remaining": len(value["items"]) - len(items), "sheets": (len(items) + 11) // 12}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["init", "ingest", "sheets"])
    parser.add_argument("id", nargs="?")
    parser.add_argument("original", nargs="?")
    parser.add_argument("--decoded", type=Path, help="Folder of actual unpacked KSP1 dish PNGs")
    args = parser.parse_args()
    if args.command == "init": init()
    elif args.command == "ingest": ingest(args.id, args.original)
    else: sheets(args.decoded)
