"""Generate display labels missing from KRC1's ID-only dictionary."""
import argparse
import json
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[1]
def build(root=ROOT):
    raw=(root/'checkpoints/2026-10-28/packages/kitchen_recipes.krc').read_bytes()
    offset,length=struct.unpack_from('<II',raw,20)
    dictionary=json.loads(raw[offset:offset+length])
    ingredients=json.loads((root/'data/ingredients.json').read_text())['ingredients']
    seasonings=json.loads((root/'data/seasonings.json').read_text())['seasonings']
    ing={x['id']:x for x in ingredients};season={x['id']:x for x in seasonings}
    if len(ing)!=len(ingredients) or len(season)!=len(seasonings):raise ValueError('duplicate IDs')
    if set(ing)!=set(dictionary['ingredients']) or set(season)!=set(dictionary['seasonings']):
        raise ValueError('metadata IDs do not match the frozen KRC dictionary')
    ordinal={name:i for i,name in enumerate(dictionary['ingredients'])}
    data={'ingredients':[{'name':ing[i]['name'],'category':ing[i]['cat'],'version':ing[i]['v']} for i in dictionary['ingredients']],
          'ingredient_order':[ordinal[x['id']] for x in ingredients],
          'fridge_order':[ordinal[x['id']] for x in ingredients if x['v']==1],
          'seasonings':[season[i]['name'] for i in dictionary['seasonings']]}
    chars=set((root/'checkpoints/2026-10-28/packages/kitchen_fonts.chars.txt').read_text())
    labels=''.join(x['name'] for x in data['ingredients'])+''.join(data['seasonings'])
    missing=sorted(set(labels)-chars)
    if missing:raise ValueError(f'font missing metadata characters: {"".join(missing)}')
    return json.dumps(data,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode('utf-8')
def build_c(root=ROOT):
    raw=(root/'checkpoints/2026-10-28/packages/kitchen_recipes.krc').read_bytes()
    offset,length=struct.unpack_from('<II',raw,20);dictionary=json.loads(raw[offset:offset+length])
    data=json.loads(build(root));ingredients=json.loads((root/'data/ingredients.json').read_text())['ingredients']
    lookup={x['id']:x for x in ingredients};q=lambda x:json.dumps(x,ensure_ascii=False)
    lines=['/* Generated by tools/build_firmware_metadata.py; do not edit. */','#include "kitchen_metadata.h"',
           f'const uint32_t km_krc_crc = 0x{struct.unpack_from("<I",raw,44)[0]:08x}u;',f'const uint32_t km_krc_size = {len(raw)}u;']
    rows=[f'    {{{q(i)}, {q(lookup[i]["name"])}, {q(lookup[i]["cat"])}, {lookup[i]["v"]}}},' for i in dictionary['ingredients']]
    lines+=['const km_ingredient km_ingredients[] = {',*rows,'};',f'const unsigned km_ingredient_count = {len(rows)};']
    for name in ('ingredient_order','fridge_order'):
        values=data[name];lines += [f'const uint8_t km_{name}[] = {{{", ".join(map(str,values))}}};',f'const unsigned km_{name}_count = {len(values)};']
    for name in ('assets','vessels','sauces','garnishes','methods','heats'):
        values=dictionary[name];lines += [f'const char *const km_{name}[] = {{{", ".join(q(x) for x in values)}}};',f'const unsigned km_{name}_count = {len(values)};']
    values=data['seasonings'];lines += [f'const char *const km_seasoning_names[] = {{{", ".join(q(x) for x in values)}}};',f'const unsigned km_seasoning_count = {len(values)};']
    return ('\n'.join(lines)+'\n').encode('utf-8')
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path);parser.add_argument('--c-output',type=Path);args=parser.parse_args()
    if not args.output and not args.c_output:parser.error('at least one output is required')
    for target,data in ((args.output,build()),(args.c_output,build_c())):
        if target:target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data);print(f'Wrote {len(data)} bytes to {target}')
if __name__=='__main__':main()
